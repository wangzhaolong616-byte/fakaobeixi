/* ============================================================
 * patch-k-fix.js  —  修正补丁：为两个原有 A 层节点补 rule 字段
 * ------------------------------------------------------------
 * 背景：MF-16、XZF-10 在 data-knowledge.js 中本已是 A 层，
 *       但其 one 字段写得过长（把分点规则塞进了「一句话」），
 *       而 rule（考试版规则）字段为空。
 * 处理：仅补 rule，把 one 中的分点内容规整搬入 rule；不改动 one。
 *       这两个节点本就是 A 层，故本文件不做 tier 升级。
 * 加载顺序：必须在 js/data-knowledge.js 之后。
 * 形式：classic script / IIFE，不使用 import / export。
 * 依据：民法典（第1165—1172条）、行政诉讼法（第25条、第26条）。
 * ============================================================ */
(function () {
  var patch = {
    'MF-16': {
      rule: '①共同侵权（有共同故意或共同过失）→ 连带责任（第1168条）。②教唆、帮助他人侵权 → 与行为人承担连带责任（第1169条）。③共同危险行为（二人以上实施危及他人人身、财产安全的行为，其中一人或数人造成损害；能确定侵权人的由其担责，不能确定的由行为人连带负责）（第1170条）。④无意思联络数人侵权：每人行为都足以造成全部损害的，承担连带责任（第1171条）；能确定责任大小的按份承担，难以确定的平均承担（第1172条）。⑤一般侵权为过错责任（第1165条），法定情形为无过错责任（第1166条）。'
    },
    'XZF-10': {
      rule: '①原告资格（第25条）：行政行为的相对人及其他与行政行为有利害关系的公民、法人或其他组织有权起诉；有权起诉的公民死亡，其近亲属可起诉。②未经复议直接起诉：作出行政行为的机关是被告。③经复议的案件：维持原行为的，原机关与复议机关是共同被告；改变的，复议机关是被告；复议机关逾期未作决定，起诉原行为的以原机关为被告，起诉其不作为的以复议机关为被告。④两个以上机关共同作出同一行政行为的，共同为被告。⑤受委托组织作出的行政行为，委托的机关是被告。⑥行政机关被撤销或职权变更的，继续行使其职权的机关是被告。'
    }
  };
  window.DATA_KNOWLEDGE.nodes.forEach(function (n) {
    var p = patch[n.id];
    if (!p) return;
    Object.keys(p).forEach(function (k) { if (p[k]) n[k] = p[k]; });
  });
})();
